import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import AxeBuilder from '@axe-core/playwright';
import { fillCarePlan } from './care-helpers';

test.use({ actionTimeout: 15000 });

test('blank observations cannot be saved and incomplete reassessment plans are explained', async ({ page }) => {
  await page.goto('/#handoff');
  const save = page.getByRole('button', { name: 'Save handoff', exact: true });
  await expect(save).toBeDisabled();
  await page.getByLabel('Observation for medical team').fill('   '); await expect(save).toBeDisabled();
  await page.getByLabel('Observation for medical team').fill('Headache began after exercise.');
  await fillCarePlan(page);
  await page.getByLabel('Reassess at', { exact: true }).fill('2020-01-01T10:00');
  await save.click(); await expect(page.getByRole('alert')).toContainText('future reassessment time');
  await expect(page.locator('.care-thread')).toHaveCount(0);
  await expect(page.getByText('This prototype has no ground connection.', { exact: false })).toBeVisible();
});

test('blackout care appends reassessment to the original packet, persists and exports the continuing record', async ({ page, context }) => {
  test.setTimeout(90000);
  await page.goto('http://127.0.0.1:4173/#handoff');
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true);
  await context.setOffline(true); await page.reload();
  await page.getByLabel('Blackout drill').check();
  await page.getByLabel('Observation for medical team').fill('Vision blur first reported at 09:00.');
  await page.getByLabel('Procedure followed', { exact: true }).selectOption('followed');
  await page.getByLabel('Procedure name', { exact: true }).fill('Vision observation demo');
  await page.getByLabel('Procedure version', { exact: true }).fill('0.2');
  await fillCarePlan(page, 'Repeat vision report under matching lighting');
  await page.getByRole('button', { name: 'Save handoff', exact: true }).click();
  const thread = page.locator('.care-thread');
  await expect(thread).toContainText('Saved on this device · blackout drill');
  await thread.getByText('Care record · 0 reassessments', { exact: true }).click();
  await expect(thread).toContainText('Vision observation demo · version 0.2');
  const form = thread.getByRole('form', { name: /Reassess Sol/ });
  await form.getByLabel('What changed after the check').fill('Crew reports no blur under the same lighting.');
  await form.getByLabel('Change reported by crew').selectOption('improved');
  await fillCarePlan(form, 'Confirm the vision report at the next scheduled check');
  await form.getByLabel('Information still missing').fill('Formal eye examination unavailable.');
  await form.getByRole('button', { name: 'Save reassessment' }).click();
  await expect(thread).toContainText('Care record · 1 reassessments');
  await expect(thread).toContainText('Vision blur first reported at 09:00.');
  await expect(thread).toContainText('Crew reports no blur under the same lighting.');
  const [file] = await Promise.all([page.waitForEvent('download'), thread.getByRole('button', { name: /Download Sol/ }).click()]);
  const packet = JSON.parse(await readFile((await file.path())!, 'utf8'));
  expect(packet.context).toBe('Vision blur first reported at 09:00.');
  expect(packet.carePlan.nextCheck).toBe('Repeat vision report under matching lighting');
  expect(packet.continuingCare.updates).toHaveLength(1);
  expect(packet.continuingCare.updates[0]).toMatchObject({ change: 'improved', observation: 'Crew reports no blur under the same lighting.' });
  expect(packet.delivery).toMatchObject({ transmittedByGhostPilot: false, receiptConfirmed: false });
  expect(packet.continuingCare.groundResponse).toBe(null);
  const [markdown] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Markdown', exact: true }).click()]);
  const report = await readFile((await markdown.path())!, 'utf8');
  expect(report).toContain('Vision observation demo · version 0.2');
  expect(report).toContain('Formal eye examination unavailable.');
  expect(report).toContain('Crew reports no blur under the same lighting.');
  await page.reload(); await page.locator('.care-thread').getByText('Care record · 1 reassessments', { exact: true }).click();
  await expect(page.locator('.care-thread')).toContainText('Crew reports no blur under the same lighting.');
  await page.evaluate(() => window.scrollTo(0, 0));
  const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
  expect(audit.violations.map(v => v.id)).toEqual([]);
  await page.screenshot({ path: 'test-results/continuing-care.png', fullPage: true });
});

test('personal movement opens original crew videos and keeps public 4DGS out of personal evidence', async ({ page }) => {
  await page.goto('/#mission'); await page.getByRole('button', { name: 'My records', exact: true }).click();
  await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>(resolve => { const r = indexedDB.open('ghostpilot-mission', 1); r.onsuccess = () => resolve(r.result); });
    const state = await new Promise<any>(resolve => { const r = db.transaction('mission').objectStore('mission').get('state'); r.onsuccess = () => resolve(r.result); });
    const ctx = { phase: 'cruise', cameraSetup: 'A', posture: 'Upright', lighting: 'Normal', clothing: 'Fitted', activity: 'Rested', quality: 'good' };
    const dates = ['2026-11-13T01:00:00Z', '2026-11-14T01:00:00Z'];
    state.references.push({ id: 'personal-ref', crewId: state.crewId, simulated: false, phase: 'cruise', establishedAt: dates[0], reason: 'Synthetic browser-test reference', records: [{ id: 'reference-reading', crewId: state.crewId, simulated: false, date: dates[0], sol: 1, measurements: { leftRange: { ...ctx, measuredAt: dates[0], recordingId: 'reference-video' } }, leftRange: 150 }] });
    const tx = db.transaction(['mission', 'recordings'], 'readwrite'); tx.objectStore('mission').put(state, 'state');
    dates.forEach((date, i) => tx.objectStore('recordings').put({ id: i ? 'current-video' : 'reference-video', crewId: state.crewId, date, sol: 1, blob: new Blob([], { type: 'video/webm' }), frames: [], leftRange: i ? 140 : 150, rightRange: 150, confidentFrames: { left: 20, right: 20 }, conditions: { ...ctx, measuredAt: date } }));
    await new Promise<void>(resolve => { tx.oncomplete = () => resolve(); }); db.close();
  });
  await page.reload(); await page.getByRole('link', { name: 'Body', exact: true }).click();
  await page.getByRole('list', { name: 'Body regions' }).getByRole('button', { name: /^E Arms/ }).click();
  await page.getByRole('button', { name: /Shoulder range/ }).click(); await page.getByRole('button', { name: 'Compare movement', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Movement' });
  await expect(dialog.getByRole('heading', { name: 'Your movement evidence' })).toBeVisible();
  await expect(dialog.getByLabel('Crew recording', { exact: true })).toBeVisible();
  await expect(dialog.getByLabel('Retained reference recording', { exact: true })).toBeVisible();
  await expect(dialog).toContainText('Matching recorded phase and conditions');
  await expect(dialog.locator('.technical-demo')).toHaveCount(0);
  await expect(dialog.locator('.pose-replay canvas')).toHaveCount(0);
  await dialog.getByText('Estimated pose replay', { exact: true }).click();
  await expect(dialog.locator('.pose-replay canvas')).toBeAttached();
});
