test('mission handoffs survive a production offline reload', async ({ page, context }) => {
  test.setTimeout(90000);
  await page.goto('http://127.0.0.1:4173/#lens');
  await expect(page.getByRole('heading', { name: 'See the bigger mission.' })).toBeVisible();
  await expect(page.locator('.lens-research')).toContainText('NASA & CSA primary sources');
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready;
    if (!navigator.serviceWorker.controller) await new Promise<void>(resolve => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }));
  });
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'See the bigger mission.' })).toBeVisible();
  await page.getByRole('button', { name: 'Try a comms blackout' }).click();
  await page.getByLabel('What should ground know?').fill('Handoff written and retained offline.');
  await page.getByRole('button', { name: 'Save onboard handoff' }).click();
  await expect(page.locator('.packet-row')).toContainText('Handoff written and retained offline.');
  await expect(page.getByText('Offline · saved on device', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator('.packet-row')).toContainText('Handoff written and retained offline.');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download Sol 42 handoff' }).click();
  expect((await downloading).suggestedFilename()).toContain('handoff-sol-42');
  const sourceDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download source list' }).click();
  const sourceFile = await sourceDownload;
  const sourcePath = await sourceFile.path();
  const exportedSources = JSON.parse(await readFile(sourcePath!, 'utf8'));
  expect(exportedSources.sources).toHaveLength(researchSources.length);
  expect(exportedSources.research.externalMeasurementsImported).toBe(false);
});
