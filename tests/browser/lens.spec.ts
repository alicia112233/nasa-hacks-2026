import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { researchSources } from '../../src/research.mjs';

test('mission lens replays evidence without leaking future observations', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/#lens');
  await expect(page.getByRole('heading', { name: 'See the bigger mission.' })).toBeVisible();
  await expect(page.locator('.lens-center > strong')).toHaveText('SOL 042');
  await expect(page.locator('.lens-center')).toContainText('2 signals to explore');
  await page.getByRole('button', { name: 'Explore Space radiation', exact: false }).click();
  await expect(page.getByRole('region', { name: 'Selected hazard evidence' })).toContainText('Not measured');
  await expect(page.getByRole('region', { name: 'Selected hazard evidence' })).toContainText('cannot identify radiation injury');
  await page.getByText('Research for this hazard', { exact: true }).click();
  await expect(page.locator('.hazard-research').getByRole('link', { name: /CSA: Monitoring radiation/ })).toHaveAttribute('href', 'https://www.asc-csa.gc.ca/eng/news/articles/2026/2026-02-26-monitoring-radiation-astronaut-health.asp');
  await expect(page.locator('.hazard-research')).toContainText('no downloadable measurements or live feed');
  await page.getByRole('button', { name: 'Explore Altered gravity', exact: false }).click();
  await expect(page.getByRole('region', { name: 'Selected hazard evidence' })).toContainText('-12% from baseline');
  await page.getByText('Research for this hazard', { exact: true }).click();
  await expect(page.locator('.hazard-research').getByRole('link', { name: 'NASA: CIPHER' })).toBeVisible();
  await expect(page.locator('.hazard-research').getByRole('link', { name: /CSA: Monitoring radiation/ })).toHaveCount(0);
  await page.getByRole('slider', { name: 'Mission replay timeline' }).press('Home');
  await expect(page.locator('.lens-center > strong')).toHaveText('SOL 029');
  await expect(page.locator('.lens-center')).not.toContainText('signals to explore');
  await page.getByRole('button', { name: 'Explore Isolation & confinement', exact: false }).click();
  await page.getByRole('button', { name: 'Investigate attention & recovery' }).click();
  await expect(page.getByRole('dialog')).toContainText('Later observations are excluded.');
  await expect(page.getByRole('dialog')).toContainText('not enough comparable history');
  await page.getByRole('button', { name: 'Close evidence' }).click();
  await page.getByRole('button', { name: 'Play mission replay' }).click();
  await expect(page.locator('.lens-center > strong')).not.toHaveText('SOL 029');
  await page.getByRole('button', { name: 'Pause mission replay' }).click();
  await page.getByRole('button', { name: 'Latest', exact: true }).click();
  await expect(page.locator('.lens-center > strong')).toHaveText('SOL 042');
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'test-results/ghostpilot-mission-lens.png', fullPage: true });
});

test('blackout handoff persists and exports traceable evidence without claiming transmission', async ({ page }) => {
  await page.goto('/#lens');
  await expect(page.getByText('Saved on device')).toBeVisible();
  await page.getByRole('button', { name: 'Try a comms blackout' }).click();
  await expect(page.getByRole('button', { name: 'End blackout drill' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('slider', { name: 'One-way planning delay' }).press('End');
  await expect(page.getByText('60 minutes', { exact: true })).toBeVisible();
  await page.getByLabel('What should ground know?').fill('Repeated the shoulder task under the same camera conditions.');
  await page.getByRole('button', { name: 'Save onboard handoff' }).click();
  await expect(page.locator('.packet-row')).toContainText('Queued on board · not transmitted');
  await page.reload();
  await expect(page.locator('.packet-row')).toContainText('Repeated the shoulder task');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download Sol 42 handoff' }).click();
  const download = await downloading;
  await download.saveAs('test-results/mission-handoff.json');
  const packet = JSON.parse(await readFile('test-results/mission-handoff.json', 'utf8'));
  expect(packet.source).toBe('simulated');
  expect(packet.observations).toHaveLength(14);
  expect(packet.communication).toEqual({ blackoutDrill: true, oneWayMinutes: 30, transmitted: false });
  expect(packet.sources).toHaveLength(researchSources.length);
  expect(packet.sources.some((source: { id: string }) => source.id === 'cans')).toBe(true);
  expect(packet.research.externalMeasurementsImported).toBe(false);
  expect(packet.analysis.flags.attention).toBe(true);
  expect(packet.status).toBe('downloaded');
  await expect(page.locator('.packet-row')).toContainText('Downloaded · not transmitted');
});

